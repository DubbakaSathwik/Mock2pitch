// Generates types/database.ts in the shape of `supabase gen types typescript` by introspecting a throw-away Postgres
// that has all migrations applied. Use the official CLI (`npm run gen:types`) when Docker is available; this exists so
// types can be produced where Docker is not (it needs only a Postgres server: PG_URL, default localhost:54329).
import pg from "pg";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASE = process.env.PG_URL ?? "postgres://postgres@localhost:54329/postgres";
const name = `m2p_types_${Date.now()}`;
const admin = new pg.Client({ connectionString: BASE });
await admin.connect();
await admin.query(`create database ${name}`);
const url = BASE.replace(/\/[^/]*$/, `/${name}`);
const db = new pg.Client({ connectionString: url });
await db.connect();
try {
  await db.query(fs.readFileSync(path.join(root, "tests/db/supabase-stub.sql"), "utf8"));
  const dir = path.join(root, "supabase/migrations");
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()) await db.query(fs.readFileSync(path.join(dir, f), "utf8"));

  const ts = (t, udt) => {
    const arr = udt.startsWith("_");
    const base = arr ? udt.slice(1) : udt;
    const m = { uuid: "string", text: "string", varchar: "string", citext: "string", bool: "boolean", int2: "number", int4: "number", int8: "number", numeric: "number", float4: "number", float8: "number", timestamptz: "string", timestamp: "string", date: "string", time: "string", jsonb: "Json", json: "Json", bytea: "string" }[base] ?? "string";
    return arr ? `${m}[]` : m;
  };
  const tables = (await db.query(`select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by 1`)).rows;
  let tablesTs = "";
  for (const { table_name: t } of tables) {
    const cols = (await db.query(`select column_name, udt_name, is_nullable='YES' nullable, column_default is not null has_default, is_identity='YES' ident from information_schema.columns where table_schema='public' and table_name=$1 order by ordinal_position`, [t])).rows;
    const row = cols.map((c) => `          ${c.column_name}: ${ts(null, c.udt_name)}${c.nullable ? " | null" : ""}`).join("\n");
    const ins = cols.map((c) => `          ${c.column_name}${c.nullable || c.has_default || c.ident ? "?" : ""}: ${ts(null, c.udt_name)}${c.nullable ? " | null" : ""}`).join("\n");
    const upd = cols.map((c) => `          ${c.column_name}?: ${ts(null, c.udt_name)}${c.nullable ? " | null" : ""}`).join("\n");
    tablesTs += `      ${t}: {\n        Row: {\n${row}\n        }\n        Insert: {\n${ins}\n        }\n        Update: {\n${upd}\n        }\n        Relationships: []\n      }\n`;
  }

  const fns = (await db.query(`
    select p.proname, p.proretset, p.pronargdefaults, p.proargnames, p.proargmodes::text[] modes,
           (select array_agg(t.typname::text order by o) from unnest(coalesce(p.proallargtypes::oid[], p.proargtypes::oid[])) with ordinality u(oid, o) join pg_type t on t.oid=u.oid) argtypes,
           rt.typname::text rettype, rt.typtype::text typtype, rt.typrelid, p.pronargs
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type rt on rt.oid=p.prorettype
    where n.nspname='public' order by p.proname`)).rows;
  let fnsTs = "";
  for (const f of fns) {
    const names = f.proargnames ?? [];
    const modes = f.modes ?? [];
    const types = f.argtypes ?? [];
    const inArgs = [], outCols = [];
    types.forEach((t, i) => {
      const mode = modes[i] ?? "i";
      const n = names[i] ?? `arg${i}`;
      if (mode === "i" || mode === "b" || mode === "v") inArgs.push({ n, t });
      else outCols.push({ n, t });
    });
    const firstDefault = inArgs.length - f.pronargdefaults;
    const args = inArgs.length ? inArgs.map((a, i) => `${a.n}${i >= firstDefault ? "?" : ""}: ${ts(null, a.t)}`).join("; ") : "never";
    let ret;
    if (outCols.length) ret = `{ ${outCols.map((c) => `${c.n}: ${ts(null, c.t)} | null`).join("; ")} }[]`;
    else if (f.typtype === "c") ret = `Database["public"]["Tables"]["${f.rettype}"]["Row"]${f.proretset ? "[]" : ""}`;
    else if (f.rettype === "void") ret = "undefined";
    else ret = ts(null, f.rettype) + (f.proretset ? "[]" : "");
    fnsTs += `      ${f.proname}: {\n        Args: ${inArgs.length ? `{ ${args} }` : "never"}\n        Returns: ${ret}\n      }\n`;
  }

  const out = `// GENERATED by scripts/gen-types.mjs from supabase/migrations. Do not edit by hand.
// Shape follows \`supabase gen types typescript\`; regenerate with the official CLI when Docker is available.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type Database = {
  public: {
    Tables: {
${tablesTs}    }
    Views: { [_ in never]: never }
    Functions: {
${fnsTs}    }
    Enums: { [_ in never]: never }
    CompositeTypes: { [_ in never]: never }
  }
}
`;
  fs.mkdirSync(path.join(root, "types"), { recursive: true });
  fs.writeFileSync(path.join(root, "types/database.ts"), out);
  console.log(`types/database.ts: ${tables.length} tables, ${fns.length} functions`);
} finally {
  await db.end();
  await admin.query(`drop database if exists ${name} with (force)`);
  await admin.end();
}
