// Generates supabase/functions/_shared/riva/descriptor.ts from the vendored .proto files, so the gRPC client needs no
// file-system access at runtime (the Supabase Edge Runtime does not expose bundled files to protobuf loaders by path).
// Run after updating the vendored protos: node scripts/gen-riva-descriptor.mjs
import protobuf from "protobufjs";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const protoRoot = path.join(root, "supabase/functions/_shared/riva");
const r = new protobuf.Root();
r.resolvePath = (_origin, target) => (path.isAbsolute(target) ? target : path.join(protoRoot, target));
await r.load("riva/proto/riva_asr.proto", { keepCase: true });
const json = r.toJSON({ keepComments: false });
fs.writeFileSync(path.join(protoRoot, "descriptor.ts"), `// GENERATED by scripts/gen-riva-descriptor.mjs from riva/proto/*.proto (Apache-2.0, NVIDIA). Do not edit by hand.
// deno-lint-ignore-file
export const RIVA_DESCRIPTOR = ${JSON.stringify(json)} as const;
`);
console.log("descriptor bytes", fs.statSync(path.join(protoRoot, "descriptor.ts")).size);
