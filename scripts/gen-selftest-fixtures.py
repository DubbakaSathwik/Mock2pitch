#!/usr/bin/env python3
"""Generates supabase/functions/_shared/selftest/fixtures.ts (a slide JPEG with text and a short TTS speech WAV).
Needs Pillow and ffmpeg with libflite. Synthetic content only."""
from PIL import Image, ImageDraw, ImageFont
import base64, subprocess, io, os, tempfile

W, H = 960, 540
im = Image.new("RGB", (W, H), (255, 255, 255)); d = ImageDraw.Draw(im)
bold = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 52)
reg = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 34)
d.rectangle([0, 0, W, 90], fill=(15, 118, 110)); d.text((40, 16), "ParkSense - Results", font=bold, fill=(255, 255, 255))
for i, t in enumerate(["94% detection accuracy", "4 second average latency", "Tested on 20 parking bays", "Cost: Rs 450 per bay"]):
    d.text((60, 150 + i * 80), "- " + t, font=reg, fill=(30, 41, 59))
buf = io.BytesIO(); im.save(buf, "JPEG", quality=70); jpg = buf.getvalue()

text = "So um we built the system, and uh it actually works. Basically, ninety four percent accuracy."
wav_path = os.path.join(tempfile.mkdtemp(), "selftest.wav")
subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", f"flite=text='{text}':voice=slt",
                "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", wav_path], check=True)
wav = open(wav_path, "rb").read()
print("jpeg bytes", len(jpg), "wav bytes", len(wav), "wav seconds", round((len(wav) - 44) / 32000, 1))

def chunks(b, n=120):
    # an array joined at load time (a long "a" + "b" chain overflows some parsers' recursion depth)
    s = base64.b64encode(b).decode()
    return "[\n" + "\n".join('  "' + s[i:i + n] + '",' for i in range(0, len(s), n)) + "\n].join(\"\")"

out = os.path.join(os.path.dirname(__file__), "../supabase/functions/_shared/selftest/fixtures.ts")
open(out, "w").write(f'''// GENERATED by scripts/gen-selftest-fixtures.py. Synthetic fixtures used only by the ops-selftest function.
// SLIDE_JPEG_B64: a 960x540 slide image with text. SPEECH_WAV_B64: flite text-to-speech, 16 kHz mono 16-bit, contains fillers.
export const SPEECH_TEXT = {text!r};

export const SLIDE_JPEG_B64 =
{chunks(jpg)};

export const SPEECH_WAV_B64 =
{chunks(wav)};

export function fromB64(b64: string): Uint8Array {{
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}}
''')
